const DICT: Record<Lang, Record<Key, string>> = { de, en };

export type UiKey = Key;
export function tr(lang: Lang, key: Key, p?: Record<string, string | number>): string {
  return fill(DICT[lang][key] ?? de[key], p);
}

export function statusLabel(lang: Lang, s: Status | undefined, late?: boolean): string {
  if (!s) return '';
  if (s === 'reached' && late) return tr(lang, 'status.reached_late');
  return tr(lang, `status.${s}` as Key);
}

export function pct(x: number | null | undefined): string {
  if (x === null || x === undefined) return '–';
  return `${Math.round(x * 100)} %`;
}
